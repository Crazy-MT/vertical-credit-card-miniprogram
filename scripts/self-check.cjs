// Run against TypeScript output supplied by npm run test:cards.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const output = path.join(__dirname, '../.test-output')
const { detectCardBrand, formatCardNumber, formatExpiry, displayCardNumber } = require(path.join(output, 'modules/vertical-credit-card/model.js'))
const { cardPresets } = require(path.join(output, 'modules/vertical-credit-card/presets.js'))
const brandCases = { '4111 2222': 'visa', '5100': 'mastercard', '2221': 'mastercard', '2720': 'mastercard', '2721': 'generic', '3400': 'americanExpress', '6011': 'discover', '622126': 'discover', '622925': 'discover', '622926': 'unionPay', '3000': 'dinersClub', '3528': 'jcb', '3589': 'jcb', '3590': 'generic', '6200': 'unionPay', '': 'generic' }
for (const [number, brand] of Object.entries(brandCases)) assert.equal(detectCardBrand(number), brand)
assert.equal(formatCardNumber('4111a222233334444555'), '4111 2222 3333 4444')
assert.equal(formatExpiry('1228'), '12/28')
assert.equal(formatExpiry('12'), '12')
assert.equal(displayCardNumber('4111 2222 3333 4444', true), '••••  ••••  ••••  4444')
assert.equal(new Set(cardPresets.map(item => item.id)).size, 46)
for (const preset of cardPresets) assert.ok(fs.existsSync(path.join(__dirname, '../miniprogram', preset.backgroundImage)), preset.id)
const assetsDirectory = path.join(__dirname, '../miniprogram/modules/vertical-credit-card/assets')
const mediaSize = fs.readdirSync(assetsDirectory).reduce((total, file) => total + fs.statSync(path.join(assetsDirectory, file)).size, 0)
assert.ok(mediaSize < 200000, `Combined card media must stay below 200 KB; got ${mediaSize} bytes`)
console.log('46 presets, assets, brand boundaries, formatting and privacy passed')
